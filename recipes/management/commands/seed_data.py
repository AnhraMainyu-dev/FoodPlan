class Command(BaseCommand):
    help = "Заполняет базу тестовыми справочниками, рецептами и ингредиентами"

    def handle(self, *args, **options):
        for item in DIETS:
            DietType.objects.update_or_create(
                index_value=item["index_value"],
                defaults=item,
            )

        for item in MEALS:
            MealType.objects.update_or_create(
                index_value=item["index_value"],
                defaults=item,
            )

        for item in PERSONS:
            PersonOption.objects.update_or_create(
                index_value=item["index_value"],
                defaults=item,
            )

        for item in DURATIONS:
            SubscriptionDuration.objects.update_or_create(
                index_value=item["index_value"],
                defaults=item,
            )

        for item in ALLERGIES:
            Allergy.objects.update_or_create(
                index_value=item["index_value"],
                defaults=item,
            )

        for name, unit in INGREDIENTS.items():
            Ingredient.objects.get_or_create(name=name, defaults={"unit": unit})

        PromoCode.objects.get_or_create(
            code="FOOD20",
            defaults={
                "discount_percent": 20,
                "valid_until": date.today() + timedelta(days=90),
                "is_active": True,
            },
        )

        for dish_data in DISHES:
            diet = DietType.objects.get(name=dish_data["diet"])
            meal = MealType.objects.get(name=dish_data["meal"])

            dish, _ = Dish.objects.update_or_create(
                title=dish_data["title"],
                defaults={
                    "description": dish_data["desc"],
                    "image": f"dishes/{dish_data['img']}",
                    "diet_type": diet,
                    "meal_type": meal,
                    "calories": dish_data["calories"],
                    "is_active": True,
                },
            )

            allergies = Allergy.objects.filter(name__in=dish_data["allergies"])
            dish.allergies.set(allergies)

            for ing_name, amount in dish_data["items"]:
                ingredient = Ingredient.objects.get(name=ing_name)
                DishIngredient.objects.update_or_create(
                    dish=dish,
                    ingredient=ingredient,
                    defaults={"amount": amount},
                )

        self.stdout.write(self.style.SUCCESS("Тестовые данные (26 блюд) успешно загружены!"))
